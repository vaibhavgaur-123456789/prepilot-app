// Production uses PostgreSQL; local development uses SQLite.
// This writes prisma/postgres/schema.prisma from the main schema with the provider switched,
// plus DIRECT_URL support (needed by Supabase/Neon connection poolers).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const src = readFileSync(path.join(root, "prisma", "schema.prisma"), "utf8");
const out = src.replace(
  /datasource db \{[^}]*\}/,
  `datasource db {\n  provider  = "postgresql"\n  url       = env("DATABASE_URL")\n  directUrl = env("DIRECT_URL")\n}`,
);
if (out === src) throw new Error("Could not find the datasource block in prisma/schema.prisma");
mkdirSync(path.join(root, "prisma", "postgres"), { recursive: true });
writeFileSync(path.join(root, "prisma", "postgres", "schema.prisma"), `// GENERATED by scripts/prisma-postgres.mjs. Edit prisma/schema.prisma instead.\n${out}`);
console.log("prisma/postgres/schema.prisma written");
